def begin(name: str) -> str:
    """Return the marker that starts the generated part ``name`` of a page."""
    return f'{{/* Generated by scripts/gen_docs.py: {name}. Do not edit this part: run `make docs`. */}}'


def end(name: str) -> str:
    """Return the marker that ends the generated part ``name`` of a page."""
    return f'{{/* End of the generated part: {name}. */}}'


def splice(page: Path, blocks: dict[str, str]) -> str:
    """Return ``page`` with the text between the markers of each named part replaced by its block."""
    text = page.read_text()
    for name, block in blocks.items():
        start, stop = begin(name), end(name)
        if start not in text or stop not in text:
            raise SystemExit(f'{page.relative_to(ROOT)} needs the markers of its generated part:\n{start}\n{stop}')
        head, rest = text.split(start, 1)
        text = f'{head}{start}\n\n{block}\n{stop}{rest.split(stop, 1)[1]}'
    return text


def doc(obj: object, what: str) -> str:
    """Return the docstring of ``obj``, cleaned. Stop when it has none: a page shows it."""
    text = getattr(obj, '__doc__', None)
    if not text or not text.strip():
        raise SystemExit(f'{what} has no docstring, and a page of the docs shows it: write one')
    return inspect.cleandoc(text)


def lead(obj: object, what: str) -> str:
    """Return the first paragraph of the docstring of ``obj``, on one line."""
    return ' '.join(doc(obj, what).split('\n\n')[0].split())


def told(obj: object, what: str) -> str:
    """Return the docstring of ``obj`` above its first section (``SECTION``), on one line: the part for users."""
    return ' '.join(SECTION.split(doc(obj, what))[0].split())


def own(cls: type, name: str) -> object:
    """Return the attribute ``name`` that ``cls`` itself defines. Stop when it only inherits one."""
    if name not in vars(cls):
        raise SystemExit(f'{cls.__name__} does not define {name}, and a page of the docs shows it')
    return vars(cls)[name]


def runtimes_table() -> str:
    """Return a table of the built-in runtimes: what each one is, its invocation, and what each command does in it."""
    head = ['Runtime', 'What it is', 'Invocation', *RUNTIME_COMMANDS.values()]
    rows = ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
    for kind, runtime in sorted(BUILTIN_RUNTIMES.items()):
        cells = [cell(told(own(runtime, m), f'{runtime.__name__}.{m}')) for m in RUNTIME_COMMANDS]
        what = cell(lead(runtime, runtime.__name__))
        rows.append(f'| `{kind}` | {what} | `{runtime.invocation}` | {" | ".join(cells)} |')
    return '\n'.join(rows) + '\n'


def runtime_protocol() -> str:
    """Return a table of the methods of the ``Runtime`` protocol, from their docstrings."""
    rows = ['| Method | What it does |', '|---|---|']
    for name, member in vars(Runtime).items():
        fn = member.__func__ if isinstance(member, classmethod) else member
        if name.startswith('_') or not inspect.isfunction(fn):
            continue
        params = ', '.join(list(inspect.signature(fn).parameters)[1:])
        kind = ' (class method)' if isinstance(member, classmethod) else ''
        rows.append(f'| `{name}({params})`{kind} | {cell(told(fn, f"Runtime.{name}"))} |')
    return '\n'.join(rows) + '\n'


def triggers_table() -> str:
    """Return a table of the built-in triggers: when each one fires, its parameters, and the role that may use it."""
    rows = ['| Trigger | Fires when | Parameters | Role |', '|---|---|---|---|']
    for kind, trigger in BUILTIN_TRIGGERS.items():
        params = ', '.join(f'`{name}`' for name in trigger.model_fields if name != 'kind') or 'none'
        role = f'`{trigger.ROLE}` only' if trigger.ROLE else 'any sweeping role'
        rows.append(f'| `{kind}` | {cell(lead(trigger, trigger.__name__))} | {params} | {role} |')
    return '\n'.join(rows) + '\n'


def _toml(value: object) -> str:
    """Return ``value`` as a TOML value: the scalars, lists and inline tables that a role's defaults hold."""
    if isinstance(value, bool):
        return str(value).lower()
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    if isinstance(value, list):
        return f'[{", ".join(_toml(v) for v in value)}]'
    if isinstance(value, dict):
        return '{ ' + ', '.join(f'{k} = {_toml(v)}' for k, v in value.items()) + ' }'
    return json.dumps(value)


def role_defaults() -> str:
    """Return the tables of the built-in roles with their default values, the keys that are unset left out."""
    tables = [
        '\n'.join(
            [f'[roles.{name}]']
            + [f'{k} = {_toml(v)}' for k, v in role.model_dump(mode='json').items() if k != 'runs' and v not in UNSET]
        )
        for name, role in Roles().all().items()
    ]
    return '```toml\n' + '\n\n'.join(tables) + '\n```\n'


