"""Generate the reference pages of the docs site and the trigger SQL. ``--check`` fails when a file is stale.

- ``docs/reference/configuration.mdx`` from ``piloop.config.ProjectConfig``.
- ``docs/reference/schema.mdx`` from the models in ``piloop/db/models.py``.
- ``piloop/db/actor_triggers.sql`` from ``piloop.db.triggers.TEMP``. Every connection loads it.
- ``piloop/db/persistent_triggers.sql`` from ``PERSISTENT``: a snapshot of what the migrations install, so that a
  trigger change shows up in a review as SQL.
- The generated part of three architecture pages, between ``BEGIN`` and ``END``: the entity-relationship diagram of
  the models, the values of the state enums, and the graph of the imports between the subpackages of ``piloop``.
"""

import ast
import inspect
import json
import re
import sys
from enum import StrEnum
from pathlib import Path
from typing import Any, get_args

from pydantic import BaseModel
from pydantic.json_schema import GenerateJsonSchema
from sqlalchemy import Column, Enum
from sqlalchemy.dialects import sqlite

from piloop.config import ProjectConfig
from piloop.db.models import Base, IdeaStatus, RunStatus, Verdict, WorkerState
from piloop.db.sql import schema_ddl
from piloop.db.triggers import persistent_sql, temp_sql
from piloop.db.triggers.fts import FTS_COLUMNS
from piloop.deprecated import BRIDGES

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / 'piloop'
CONFIG_PAGE = ROOT / 'docs' / 'reference' / 'configuration.mdx'
SCHEMA_PAGE = ROOT / 'docs' / 'reference' / 'schema.mdx'
DATA_MODEL_PAGE = ROOT / 'docs' / 'architecture' / 'data-model.mdx'
STATES_PAGE = ROOT / 'docs' / 'architecture' / 'state-machines.mdx'
LAYOUT_PAGE = ROOT / 'docs' / 'architecture' / 'code-layout.mdx'
ACTOR_SQL = ROOT / 'piloop' / 'db' / 'actor_triggers.sql'
PERSISTENT_SQL = ROOT / 'piloop' / 'db' / 'persistent_triggers.sql'
STATE_ENUMS: tuple[type[StrEnum], ...] = (IdeaStatus, RunStatus, WorkerState, Verdict)
BEGIN = '{/* Generated by scripts/gen_docs.py up to the end marker. Do not edit this part: run `make docs`. */}'
END = '{/* End of the generated part. */}'
REPO = 'https://github.com/hiloopai/piloop/blob/main'
JsonSchema = dict[str, Any]  # JSON Schema is untyped by nature

GENERATED = '{/* Generated by scripts/gen_docs.py. Do not edit this file: change the source and run `make docs`. */}'
CONFIG_HEADER = f"""---
title: Configuration
description: Every key of piloop.toml, with its type and its default.
---

{GENERATED}

`piloop.toml` is at the root of the project repo. `piloop init` reads it again each time you run it, and stores a
copy. The daemon uses that copy, so an edit takes effect only when you run `piloop init`.

To override a key when `piloop init` reads the file, set `PILOOP_PROJECT_<KEY>`. Join nested keys with `__`, for
example `PILOOP_PROJECT_RUNTIME=herdr` or `PILOOP_PROJECT_ROLES__WORKER__MAX_CONCURRENT=2`. The stored copy keeps the
override until the next `piloop init`. The variable has no effect on `piloop serve`.

A type in the tables links to the section that describes it. A table that you leave out has the defaults of its
section.

## Top-level keys

"""
SCHEMA_HEADER = f"""---
title: Database schema
description: The tables that piloop sql reads and writes.
---

{GENERATED}

Every client reads and writes one SQLite database, `$PILOOP_HOME/piloop.db`. Run one statement with `piloop sql`.
`piloop schema` prints the same tables with the conventions that agents follow. The agents' procedures are in
[sql_procedures.md]({REPO}/piloop/agents/prompts/sql_procedures.md).

The indexes are part of the contract: they show which filters are cheap. The [data model](/architecture/data-model)
shows the same tables as a diagram.

```sql
"""
CODE = re.compile(r'(``.+?``|`[^`]+`)')


def mdx(text: str) -> str:
    """Make docstring text safe for MDX: code spans with one backtick, and ``{}<>`` escaped outside code."""
    out = []
    for i, part in enumerate(CODE.split(text)):
        if i % 2:
            out.append(f'`{part.strip("`")}`')
        else:
            out.append(re.sub(r'([{}<>])', r'\\\1', part))
    return ''.join(out)


def cell(text: str) -> str:
    """Make text safe for one cell of a Markdown table."""
    return mdx(' '.join(text.split())).replace('|', '\\|')


def _anchor(name: str) -> str:
    return f'[{name}](#{name.lower()})'


def _type(prop: JsonSchema, defs: JsonSchema) -> str:
    if '$ref' in prop:
        name = str(prop['$ref']).rsplit('/', 1)[-1]
        target = defs[name]
        return _anchor(name) if 'properties' in target else _type(target, defs)
    if 'anyOf' in prop:
        return ' \\| '.join(_type(p, defs) for p in prop['anyOf'])
    if 'enum' in prop:
        return ' \\| '.join(f'`{v}`' for v in prop['enum'])
    t = str(prop.get('type', 'object'))
    if t == 'array' and 'prefixItems' in prop:  # a fixed-shape tuple
        return f'tuple\\[{", ".join(_type(p, defs) for p in prop["prefixItems"])}\\]'
    if t == 'array':
        return f'list\\[{_type(prop["items"], defs)}\\]'
    if t == 'object' and 'additionalProperties' in prop:
        return f'dict\\[string, {_type(prop["additionalProperties"], defs)}\\]'
    return t


def _default(name: str, prop: JsonSchema, schema: JsonSchema) -> str:
    if name in schema.get('required', []):
        return 'required'
    if '$ref' in prop and isinstance(prop.get('default'), dict):
        return '`{}`'  # a nested table left out: every key at the default that its own table shows
    return f'`{json.dumps(prop.get("default"))}`'


def _table(schema: JsonSchema, defs: JsonSchema, only: set[str] | None = None) -> str:
    rows = ['| Key | Type | Default | Description |', '|---|---|---|---|']
    for name, prop in schema['properties'].items():
        if only is not None and name not in only:
            continue
        desc = cell(str(prop.get('description', '')))
        rows.append(f'| `{name}` | {_type(prop, defs)} | {_default(name, prop, schema)} | {desc} |')
    return '\n'.join(rows) + '\n'


def _schema(model: type[BaseModel]) -> JsonSchema:
    return model.model_json_schema(schema_generator=GenerateJsonSchema)


def _section(model: type[BaseModel], defs: JsonSchema, only: set[str] | None = None) -> str:
    schema = _schema(model)
    return f'\n## {model.__name__}\n\n{mdx(schema.get("description", ""))}\n\n{_table(schema, defs, only)}'


def _nested(model: type[BaseModel], found: list[type[BaseModel]]) -> list[type[BaseModel]]:
    """Return the models reachable from the fields of ``model``, in declaration order, each once."""
    for field in model.model_fields.values():
        for sub in _models_in(field.annotation):
            if sub not in found:
                found.append(sub)
                _nested(sub, found)
    return found


def _models_in(annotation: object) -> list[type[BaseModel]]:
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return [annotation]
    return [m for arg in get_args(annotation) for m in _models_in(arg)]


def _own_keys(model: type[BaseModel], base: type[BaseModel]) -> set[str]:
    """Return the keys that ``model`` adds to ``base`` or gives another default."""
    mine, theirs = _schema(model)['properties'], _schema(base)['properties']
    return {name for name, prop in mine.items() if theirs.get(name) != prop}


def config_page() -> str:
    """Return the configuration reference: the top-level keys, then one table per nested model.

    A model that subclasses another config model gets the table of its base once (the keys that they share), and
    then a table of its own keys and defaults.
    """
    top = _schema(ProjectConfig)
    defs = top.get('$defs', {})
    out = CONFIG_HEADER + _table(top, defs)
    shown: list[type[BaseModel]] = []
    for model in _nested(ProjectConfig, []):
        base = model.__mro__[1]
        if base is BaseModel or not issubclass(base, BaseModel):
            out += _section(model, defs)
            continue
        if base not in shown:
            shown.append(base)
            out += _section(base, defs)
        out += _section(model, defs, _own_keys(model, base))
    return out + deprecated_section()


def deprecated_section() -> str:
    """Return the keys that ``piloop.deprecated`` still accepts, one bullet per bridge; nothing when there are none."""
    if not BRIDGES:
        return ''
    bullets = '\n'.join(f'- {mdx(" ".join(str(inspect.getdoc(b)).split()))}' for b in BRIDGES)
    return (
        '\n## Deprecated keys\n\nThese keys still work. Each one shows a `PiloopDeprecationWarning` that names the file,'
        ' the key, its replacement and the release that removes it. The changelog lists them too.\n\n'
        f'{bullets}\n'
    )


def splice(page: Path, block: str) -> str:
    """Return ``page`` with the text between its ``BEGIN`` and ``END`` markers replaced by ``block``."""
    text = page.read_text()
    if BEGIN not in text or END not in text:
        raise SystemExit(f'{page.relative_to(ROOT)} needs the markers of its generated part:\n{BEGIN}\n{END}')
    head, rest = text.split(BEGIN, 1)
    return f'{head}{BEGIN}\n\n{block}\n{END}{rest.split(END, 1)[1]}'


def _column_type(column: Column[object]) -> str:
    if isinstance(column.type, Enum) and column.type.enum_class is not None:
        return column.type.enum_class.__name__
    return column.type.compile(dialect=sqlite.dialect()).split('(')[0].lower()


def data_model() -> str:
    """Return a Mermaid entity-relationship diagram of every table, with its columns, and one line per foreign key."""
    lines = ['```mermaid', 'erDiagram']
    tables = list(Base.metadata.tables.values())
    for table in tables:
        lines.append(f'    {table.name} {{')
        for column in table.columns:
            keys = [
                k
                for k, on in (
                    ('PK', column.primary_key),
                    ('FK', bool(column.foreign_keys)),
                    ('UK', bool(column.unique)),
                )
                if on
            ]
            lines.append(f'        {_column_type(column)} {column.name} {",".join(keys)}'.rstrip())
        lines.append('    }')
    for table in tables:
        for column in table.columns:
            for fk in sorted(column.foreign_keys, key=lambda fk: fk.target_fullname):
                parent = '|o' if column.nullable else '||'
                lines.append(f'    {fk.column.table.name} {parent}--o{{ {table.name} : "{column.name}"')
    indexes = ', '.join(f'`{t}_fts` ({", ".join(f"`{c}`" for c in cols)})' for t, cols in FTS_COLUMNS.items())
    return '\n'.join([*lines, '```', '', f'The full-text indexes are not in the diagram: {indexes}.', ''])


def state_values() -> str:
    """Return a table of the state enums: the columns that store each one, and every value."""
    rows = ['| Enum | Column | Values |', '|---|---|---|']
    for enum in STATE_ENUMS:
        columns = [
            f'`{table.name}.{column.name}`'
            for table in Base.metadata.tables.values()
            for column in table.columns
            if isinstance(column.type, Enum) and column.type.enum_class is enum
        ]
        values = ', '.join(f'`{member.value}`' for member in enum)
        rows.append(f'| `{enum.__name__}` | {", ".join(columns)} | {values} |')
    return '\n'.join(rows) + '\n'


def _node(path: Path) -> str:
    """Return the top-level subpackage or module of ``piloop`` that the file ``path`` belongs to."""
    return path.relative_to(PACKAGE).parts[0].removesuffix('.py')


def _imported(tree: ast.Module) -> set[str]:
    """Return the top-level subpackages and modules of ``piloop`` that the import statements of ``tree`` name."""
    found: set[str] = set()
    for stmt in ast.walk(tree):
        if isinstance(stmt, ast.Import):
            names = [alias.name for alias in stmt.names]
        elif isinstance(stmt, ast.ImportFrom) and stmt.module == 'piloop':
            names = [f'piloop.{alias.name}' for alias in stmt.names]
        elif isinstance(stmt, ast.ImportFrom) and stmt.module is not None:
            names = [stmt.module]
        else:
            continue
        found |= {name.split('.')[1] for name in names if name.startswith('piloop.')}
    return found


def imports() -> dict[str, set[str]]:
    """Return, for each top-level subpackage and module of ``piloop``, the other ones that it imports."""
    graph: dict[str, set[str]] = {}
    for path in sorted(PACKAGE.rglob('*.py')):
        node = _node(path)
        if not node.startswith('__'):
            graph.setdefault(node, set()).update(_imported(ast.parse(path.read_text())) - {node})
    return graph


def _leaves(graph: dict[str, set[str]]) -> set[str]:
    """Return the top-level modules that import nothing from ``piloop`` but other such modules."""
    modules = {p.stem for p in PACKAGE.glob('*.py')} & graph.keys()
    leaves: set[str] = set()
    while grown := {m for m in modules - leaves if graph[m] <= leaves}:
        leaves |= grown
    return leaves


def _reachable(graph: dict[str, set[str]], start: str) -> set[str]:
    seen: set[str] = set()
    todo = [start]
    while todo:
        for nxt in graph[todo.pop()] - seen:
            seen.add(nxt)
            todo.append(nxt)
    return seen


def _label(node: str) -> str:
    return f'{node}/' if (PACKAGE / node).is_dir() else f'{node}.py'


def code_layout() -> str:
    """Return the import graph of the subpackages as a Mermaid flowchart, and a table of every direct import.

    The flowchart leaves out the shared leaf modules and every arrow that a longer path already implies, so that the
    layers show.
    """
    graph = imports()
    leaves = _leaves(graph)
    inner = {node: deps - leaves for node, deps in graph.items() if node not in leaves}
    lines = ['```mermaid', 'flowchart TB', *(f'    {node}["{_label(node)}"]' for node in sorted(inner))]
    for node, deps in sorted(inner.items()):
        for dep in sorted(deps):
            if not any(dep in _reachable(inner, other) for other in deps - {dep}):
                lines.append(f'    {node} --> {dep}')
    shared = ', '.join(f'`{_label(leaf)}`' for leaf in sorted(leaves))
    rows = ['| Subpackage or module | Imports directly |', '|---|---|']
    for node, deps in sorted(graph.items()):
        rows.append(f'| `{_label(node)}` | {", ".join(f"`{_label(d)}`" for d in sorted(deps)) or "nothing"} |')
    note = f'The graph leaves out the shared modules {shared}. Every layer may import them.'
    return '\n'.join([*lines, '```', '', note, '', *rows, ''])


def main(check: bool) -> int:
    """Write every generated file, or with ``check`` report the stale ones and write nothing."""
    outputs = {
        CONFIG_PAGE: config_page(),
        SCHEMA_PAGE: SCHEMA_HEADER + schema_ddl() + '\n```\n',
        DATA_MODEL_PAGE: splice(DATA_MODEL_PAGE, data_model()),
        STATES_PAGE: splice(STATES_PAGE, state_values()),
        LAYOUT_PAGE: splice(LAYOUT_PAGE, code_layout()),
        ACTOR_SQL: temp_sql(),
        PERSISTENT_SQL: persistent_sql(),
    }
    stale = [p for p, text in outputs.items() if not p.is_file() or p.read_text() != text]
    if check:
        for p in stale:
            print(f'stale: {p.relative_to(ROOT)} (run `make docs`)', file=sys.stderr)
        return 1 if stale else 0
    for p, text in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    return 0


if __name__ == '__main__':
    raise SystemExit(main(check='--check' in sys.argv[1:]))
